def sha(data):
    return hashlib.sha256(data).hexdigest()

def get_root():
    here = Path(__file__).resolve().parent
    if here.name != 'Interplex_MES_FE':
        raise RuntimeError('Updater must reside in Interplex_MES_FE (sibling of Interplex_MES_BE).')
    root = here.parent
    if not (root/'Interplex_MES_BE').is_dir():
        raise RuntimeError('Interplex_MES_BE sibling directory is missing.')
    if Path.cwd().resolve() != (root/'Interplex_MES_BE').resolve():
        raise RuntimeError('Run with current directory = Interplex_MES_BE.')
    return root

def payload():
    content = {}
    with zipfile.ZipFile(io.BytesIO(base64.b64decode(ZIP_B64))) as z:
        for path, spec in MANIFEST.items():
            content[path] = z.read(path)
            if sha(content[path]) != spec['after']:
                raise RuntimeError('Corrupt embedded payload for '+path)
    return content

def verify_sources(root):
    states = {}
    for name, spec in MANIFEST.items():
        dst = root/name
        if dst.is_symlink():
            states[name] = 'REJECT_SYMLINK'
            continue
        actual = sha(dst.read_bytes()) if dst.is_file() else None
        if actual == spec['before']:
            state = 'BEFORE'
        elif actual == spec['after']:
            state = 'AFTER'
        else:
            state = 'REJECT_'+str(actual)
        states[name]=state
    return states

def verdict(states):
    statuses = set(states.values())
    if statuses == {'BEFORE'}:return 'READY'
    if statuses == {'AFTER'}:return 'INSTALLED'
    return 'REJECT'

def branch(repo):
    try:
        p = subprocess.run(['git', '-C', str(repo), 'branch', '--show-current'],
                           capture_output=True,text=True,timeout=3,check=False)
        return p.stdout.strip() if p.returncode==0 else 'unknown'
    except Exception:return 'unknown'

def show(root):
    states=verify_sources(root)
    print(f'=== {VERSION} ===')
    print('[INFO] BE branch:',branch(root/'Interplex_MES_BE'))
    print('[INFO] FE branch:',branch(root/'Interplex_MES_FE'))
    for name,state in states.items():print('[%s] %s'%(state,name))
    v=verdict(states)
    print('VERDICT:',v)
    if v=='REJECT':
        print('REJECT: source differs from reviewed baseline or partial patch. No files were changed.')
        print('Use --collect for a read-only ZIP of current target files, then request a new compatible updater.')
    return v

def backup_dir():
    return Path.home()/'.ipth_mes_updater_backups'/VERSION

def atomic(path, raw):
    path.parent.mkdir(parents=True,exist_ok=True)
    fd,temp = tempfile.mkstemp(prefix='.mes2_',dir=path.parent)
    try:
        with os.fdopen(fd,'wb') as f:
            f.write(raw)
            f.flush()
            os.fsync(f.fileno())
        os.replace(temp,path)
    finally:
        if os.path.exists(temp):os.unlink(temp)

def get_old_bytes(root):
    return {p:((root/p).read_bytes() if (root/p).is_file() else None) for p in MANIFEST}

def restore(root, originals):
    for name,data in originals.items():
        dst=root/name
        if data is None:
            if dst.exists():dst.unlink()
        else:atomic(dst,data)

def write_backup(root, originals):
    folder=backup_dir()
    folder.mkdir(parents=True,exist_ok=True)
    final=folder/('before_'+time.strftime('%Y%m%dT%H%M%S')+'.zip')
    fd,temp=tempfile.mkstemp(prefix='.backup_',dir=folder)
    os.close(fd)
    try:
        with zipfile.ZipFile(temp,'w',zipfile.ZIP_DEFLATED) as z:
            z.writestr('BACKUP_MANIFEST.json',json.dumps(
                {'version':VERSION,'expected':MANIFEST,'files':{p:(sha(b) if b is not None else None) for p,b in originals.items()}},indent=2))
            for name,data in originals.items():
                if data is not None:z.writestr('BACKUP_FILES/'+name,data)
        os.replace(temp,final)
    finally:
        if os.path.exists(temp):os.unlink(temp)
    return final

def apply(root):
    v=show(root)
    if v=='INSTALLED':
        print('[NO-OP] Updater has already been applied.');return 0
    if v!='READY':return 2
    raw=payload()
    originals=get_old_bytes(root)
    backup=write_backup(root,originals)
    print('[BACKUP]',backup)
    try:
        for name,data in raw.items():
            atomic(root/name,data)
            print('[APPLIED]',name)
        if verdict(verify_sources(root))!='INSTALLED':raise RuntimeError('Post-apply verification failed.')
    except Exception:
        restore(root,originals)
        print('[ROLLBACK] Restored files after failed apply.')
        raise
    print('APPLIED: FE/BE code and Markdown ONLY. No DB operations.')
    print('Restart BE, rebuild FE (npm run build), then manually test on Dev.')
    return 0

def rollback(root):
    if show(root)!='INSTALLED':
        print('REJECT: rollback requires complete exact AFTER state.');return 2
    folder=backup_dir()
    backups=sorted(folder.glob('before_*.zip'),reverse=True)
    if not backups:
        print('REJECT: no updater backup present.');return 2
    prior=backups[0]
    with zipfile.ZipFile(prior) as z:
        meta=json.loads(z.read('BACKUP_MANIFEST.json'))
        if meta.get('version')!=VERSION or meta.get('expected')!=MANIFEST:
            print('REJECT: backup manifest incompatible.');return 2
        originals={}
        for name,oldhash in meta['files'].items():
            data=z.read('BACKUP_FILES/'+name) if oldhash is not None else None
            if data is not None and sha(data)!=oldhash:raise RuntimeError('Backup hash mismatch: '+name)
            originals[name]=data
    restore(root,originals)
    if verdict(verify_sources(root))!='READY':raise RuntimeError('Post-rollback verification FAILED')
    print('[ROLLBACK PASS] Restored source from',prior)
    print('Note: if BE still running, restart it. This updater has no database rollback.')
    return 0

def collect(root):
    out=Path.home()/'Downloads'
    out.mkdir(parents=True,exist_ok=True)
    dst=out/('IPTH_Workstation_RW_QA_Source_'+time.strftime('%Y%m%dT%H%M%S')+'.zip')
    with zipfile.ZipFile(dst,'w',zipfile.ZIP_DEFLATED) as z:
        for name in MANIFEST:
            f=root/name
            if f.is_file() and not f.is_symlink():z.write(f,name)
        z.writestr('COLLECT_MANIFEST.json',json.dumps({'version':VERSION,'sha':{
            name:(sha((root/name).read_bytes()) if (root/name).is_file() else None)
            for name in MANIFEST}},indent=2))
    print('[COLLECTED]',dst)
    print('Review ZIP contents before sharing; only specified source/doc files were included.')
    return 0

def self_test(root):
    source=(root/'Interplex_MES_BE/app/api/v1/endpoints/qc_batch_hold.py').read_text()
    tree=ast.parse(source)
    funcs=[n for n in tree.body if isinstance(n,ast.FunctionDef) and n.name=='eligible']
    if len(funcs)!=1:raise RuntimeError('eligible function not found')
    isolated=ast.Module(body=funcs,type_ignores=[])
    ns={}
    exec(compile(ast.fix_missing_locations(isolated),'<eligible>','exec'),ns)
    from types import SimpleNamespace
    cases=[('QA','operator',True),('qa ','operator',True),('IT','operator',True),
           ('QC','operator',True),('Production','admin',False),('Production','operator',False),
           ('Production','QA',True)]
    for dept,role,want in cases:
        got=ns['eligible'](SimpleNamespace(dept=dept,role=role))
        if got!=want:raise RuntimeError(f'eligible({dept},{role})={got} expected {want}')
    print('[PASS] QA/QC/IT eligibility checks (7 cases). No database changes.')
    return 0

def main():
    parser=argparse.ArgumentParser(description=VERSION)
    actions=parser.add_mutually_exclusive_group(required=True)
    for action in ['scan','apply','verify','rollback','collect','self-test']:
        actions.add_argument('--'+action,action='store_true')
    args=parser.parse_args()
    root=get_root()
    if args.scan:return 0 if show(root)!='REJECT' else 2
    if args.apply:return apply(root)
    if args.verify:return 0 if show(root)=='INSTALLED' else 2
    if args.rollback:return rollback(root)
    if args.collect:return collect(root)
    if args.self_test:return self_test(root)
    return 2

if __name__=='__main__':
    try:sys.exit(main())
    except Exception as exc:
        print('FATAL:',repr(exc),file=sys.stderr)
        sys.exit(3)
